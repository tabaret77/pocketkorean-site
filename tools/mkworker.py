"""Writes _worker.js (Cloudflare Pages advanced mode) from lib/pk.js.
Pages runs _worker.js as-is, with no Functions build step; _routes.json limits it to word and name URLs."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def build():
    src = open(os.path.join(ROOT, 'lib', 'pk.js'), encoding='utf-8').read()
    src = re.sub(r'^export ', '', src, flags=re.M)
    out = src + r'''
const ROUTE = /^\/([a-z-]+)\/(word|name)\/(.*)$/;
export default {
  async fetch(request, env, wctx) {
    const url = new URL(request.url);
    const m = url.pathname.match(ROUTE);
    if (!m) return env.ASSETS.fetch(request);
    const rest = m[3].split('/').filter(Boolean);
    const ctx = { request, env, params: { lang: m[1], path: rest }, next: () => env.ASSETS.fetch(request), waitUntil: (p) => wctx.waitUntil(p) };
    try {
      return await (m[2] === 'word' ? wordPage(ctx) : namePage(ctx));
    } catch (e) {
      return new Response('Error: ' + (e && e.stack || e), { status: 500, headers: { 'content-type': 'text/plain; charset=utf-8', 'cache-control': 'no-store' } });
    }
  },
};
'''
    open(os.path.join(ROOT, '_worker.js'), 'w', encoding='utf-8').write('// generated by tools/mkworker.py from lib/pk.js — edit lib/pk.js instead\n' + out)

if __name__ == '__main__':
    build()
